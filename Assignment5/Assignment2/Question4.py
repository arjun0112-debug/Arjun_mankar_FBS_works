# WAP to calculate area of triangle and rectangle

B = float(input("Enter the base : "))
h = float(input("Emter the height : "))
l = float(input("Enter the length : "))
b = float(input("Enter the breadth : "))

#Area of triangle

Area_triangle = 0.5 * h * B 

#Area of rectangle

Area_rectangle = l * b

print(f'Area of triangle is {Area_triangle}, \n Area of rectangle is {Area_rectangle}')